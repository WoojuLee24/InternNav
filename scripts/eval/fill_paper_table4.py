#!/usr/bin/env python3
"""fill_paper_table4.py — Fill paper Table 4 (VisionEmbeddingCache A/B) from B2 results.

Usage:
    python scripts/eval/fill_paper_table4.py

Reads:
    /mnt/nvme0/vln_habitat/logs/vln_ce_b2/uncached/timing_rank0.json
    /mnt/nvme0/vln_habitat/logs/vln_ce_b2/cached/timing_rank0.json
    /mnt/nvme0/vln_habitat/logs/vln_ce_b2/uncached/progress_rank0.json
    /mnt/nvme0/vln_habitat/logs/vln_ce_b2/cached/progress_rank0.json

Writes to stdout: LaTeX table rows ready to paste into nexusnav_v3.tex Table 4.
Also writes: paper/b2_results.json for provenance tracking.
"""

import json
import os
import sys
from pathlib import Path
from statistics import mean

BASE = Path("/mnt/nvme0/vln_habitat/logs/vln_ce_b2")
PAPER_DIR = Path(__file__).parent.parent.parent / "paper"


def load_json(path):
    try:
        return json.loads(Path(path).read_text())
    except Exception as e:
        print(f"[ERROR] Cannot read {path}: {e}", file=sys.stderr)
        return None


def load_progress(path):
    """Parse progress_rank0.json (one JSON object per line)."""
    try:
        lines = Path(path).read_text().strip().split("\n")
        rows = [json.loads(l) for l in lines if l.strip()]
        n = len(rows)
        sr = sum(r["success"] for r in rows) / n if n else 0.0
        spl = sum(r["spl"] for r in rows) / n if n else 0.0
        ne = sum(r["ne"] for r in rows) / n if n else 0.0
        return {"n": n, "SR": round(sr * 100, 1), "SPL": round(spl * 100, 1), "NE": round(ne, 2)}
    except Exception as e:
        print(f"[ERROR] Cannot parse {path}: {e}", file=sys.stderr)
        return None


def main():
    uncached_timing = load_json(BASE / "uncached" / "timing_rank0.json")
    cached_timing = load_json(BASE / "cached" / "timing_rank0.json")
    uncached_prog = load_progress(BASE / "uncached" / "progress_rank0.json")
    cached_prog = load_progress(BASE / "cached" / "progress_rank0.json")

    missing = []
    if uncached_timing is None: missing.append("B2-uncached timing")
    if cached_timing is None: missing.append("B2-cached timing")
    if uncached_prog is None: missing.append("B2-uncached progress")
    if cached_prog is None: missing.append("B2-cached progress")
    if missing:
        print(f"[MISSING] Waiting for: {', '.join(missing)}")
        print("[INFO] Run cap_and_launch_b2.sh first, then re-run this script.")
        sys.exit(1)

    # ── Compute speedup ────────────────────────────────────────────────────────
    s2_ms_unc = uncached_timing.get("s2_ms", float("nan"))
    s2_ms_cac = cached_timing.get("s2_ms", float("nan"))
    s2_hz_unc = uncached_timing.get("s2_hz", float("nan"))
    s2_hz_cac = cached_timing.get("s2_hz", float("nan"))
    hit_rate = cached_timing.get("cache_hit_rate", float("nan"))
    hit_pct = round(hit_rate * 100, 1) if hit_rate == hit_rate else float("nan")
    speedup = round(s2_ms_unc / s2_ms_cac, 2) if s2_ms_cac and s2_ms_cac > 0 else float("nan")
    delta_sr = round(cached_prog["SR"] - uncached_prog["SR"], 1)

    # ── Print LaTeX rows ───────────────────────────────────────────────────────
    print("% ── Table 4 rows — generated by fill_paper_table4.py ──")
    print(r"% Replace the two placeholder rows in \label{tab:vision_cache_ab}")
    print()
    print(r"\midrule")
    print(
        f"B2 Uncached (baseline) & {s2_ms_unc:.0f} & {s2_hz_unc:.2f} & 0.0 & {uncached_prog['SR']} \\\\"
    )
    print(
        f"B2 Cached ($\\tau=0.92$) & {s2_ms_cac:.0f} & {s2_hz_cac:.2f} & {hit_pct} & {cached_prog['SR']} \\\\"
    )
    print(r"\midrule")
    print(
        f"Speedup & {speedup:.1f}$\\times$ & {speedup:.1f}$\\times$ & — & ${delta_sr:+.1f}$ \\\\"
    )
    print()

    # ── Print summary ──────────────────────────────────────────────────────────
    print("=" * 60)
    print(f"B2 Uncached: n={uncached_prog['n']} SR={uncached_prog['SR']}% SPL={uncached_prog['SPL']}% NE={uncached_prog['NE']}")
    print(f"B2 Cached:   n={cached_prog['n']}  SR={cached_prog['SR']}%  SPL={cached_prog['SPL']}%  NE={cached_prog['NE']}")
    print(f"S2 latency:  {s2_ms_unc:.0f}ms → {s2_ms_cac:.0f}ms  ({speedup:.1f}x speedup)")
    print(f"Cache hit rate: {hit_pct}%  (expected ~60-80%)")
    print(f"SR delta: {delta_sr:+.1f}% (should be ≈0 if cache is lossless)")
    print("=" * 60)

    # ── Write provenance JSON ──────────────────────────────────────────────────
    result = {
        "generated_by": "fill_paper_table4.py",
        "b2_uncached": {"timing": uncached_timing, "progress": uncached_prog},
        "b2_cached": {"timing": cached_timing, "progress": cached_prog},
        "speedup_x": speedup,
        "cache_hit_pct": hit_pct,
        "delta_sr": delta_sr,
    }
    out = PAPER_DIR / "b2_results.json"
    out.write_text(json.dumps(result, indent=2))
    print(f"\n[provenance] Written to {out}")
    print("[next step] Paste the LaTeX rows above into nexusnav_v3.tex Table 4 \\midrule block.")
    print("[next step] Drop result paths to debug-duilvn-metrics-validation peer session.")


if __name__ == "__main__":
    main()
