"""노은역(GT 없는 씬) 경로를 **vln_ce 포맷**으로 내보낸다.

`gs_vlnpe/05_export_vlnce.py`(mp3d)와 같은 05단계·같은 출력 포맷이지만, **만드는 방법이 다르다**.

| | `gs_vlnpe/05_export_vlnce` (mp3d) | 이 파일 (노은역) |
|---|---|---|
| 경로 | GT pose 재생 | **우리가 계획한 경로** (`03 --mode random`) |
| action | GT에서 복사 | **이산화해서 만든다** (`vlnce_discretize`) |
| 픽셀 목표 | GT에서 복사 | **계산한다** (`vlnce_pixel_goal`) |
| parquet·meta | GT에서 바이트 복사 | **직접 쓴다** (`vlnce_writer`) |
| 지시문 | GT에서 복사 | **placeholder** — 이후 `vln-annotator`가 채운다 |

GT를 **전혀 안 본다.** 그게 이 작업의 목적이다 — GT 없는 실제 환경에서 우리 경로·렌더로
학습 데이터를 만드는 것.

왜 이산화가 필수인가
--------------------
vln_ce는 **프레임 하나 = 이산 action 하나**다(릴리스 실측: 전진 0.2500 m/회전 0°,
회전 15.00°/이동 0 m). 우리 경로는 연속이라 그대로는 못 쓴다. **제자리 회전 프레임이
실제로 존재**하므로 단순 리샘플로는 재현이 안 된다.

(`--frame_step_m`은 vln_pe용이다. vln_ce의 간격은 이산 action이 정한다 — 전진 0.25 m 고정.)

rig 5개
-------
릴리스와 같은 세팅으로 5개를 전부 만든다. **경로는 하나고 카메라만 5벌**이다
(릴리스 parquet에 `action` 컬럼이 하나뿐인 것으로 확인).
한 프로세스에서 `build_renderer`를 두 번 부르면 죽으므로 rig당 프로세스 하나로 돈다.

커맨드
------
스모크 (2 에피소드 × rig 1개):
timeout --signal=KILL 3600 /workspace/isaaclab/_isaac_sim/python.sh scripts/dataset_converters/gs_vlnpe/apply_real/05_export_vlnce.py --scene noeun_station_mid --rigs 125cm_30deg --max_episodes 2 --out_root data/InternData-N1-v0.5-mini/vln_ce_noeun --log_dir logs/gs-vlnpe/apply_real

전체 (20 에피소드 × rig 5개 ≈ 9,440 렌더):
timeout --signal=KILL 28800 /workspace/isaaclab/_isaac_sim/python.sh scripts/dataset_converters/gs_vlnpe/apply_real/05_export_vlnce.py --scene noeun_station_mid --rigs all --max_episodes 0 --out_root data/InternData-N1-v0.5-mini/vln_ce_noeun --log_dir logs/gs-vlnpe/apply_real

⚠️ 씬 폴더 이름에 `_`를 넣지 않는다 — `internnav/utils/loader.py:158-175`가 `key.split('_')`로
되돌려서 `noeun_station_mid`가 `noeun`으로 잘린다. 기본 출력 이름은 `noeunstationmid`다.
"""

