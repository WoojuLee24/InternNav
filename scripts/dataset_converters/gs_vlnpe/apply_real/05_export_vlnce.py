def assemble(args, rigs: list, sentinel_dir: Path) -> dict:
    import vlnce_pixel_goal as vpg
    import vlnce_writer as vw
    from PIL import Image

    out_root = Path(args.out_root) / 'traj_data' / 'r2r'
    O = scene_paths(out_root, args.out_scene)
    schema = vw.load_schema(args.schema_ref)
    schema_rigs = vw.rigs_in_schema(schema)
    missing = [r for r in schema_rigs if r not in rigs]
    if missing:
        print(f'[{SCRIPT_NAME}] 경고 — 렌더 안 된 rig {missing}는 parquet에 센티널로 채운다',
              flush=True)

    store = {r: np.load(sentinel_dir / f'pose__{r}.npz') for r in rigs}
    n_eps = len({k.split('_')[1] for k in store[rigs[0]].files if k.startswith('pose_')})

    # meta는 append 방식이라 재실행 시 중복된다 — 먼저 비운다
    O['meta_dir'].mkdir(parents=True, exist_ok=True)
    for name in ('episodes.jsonl', 'tasks.jsonl', 'episodes_stats.jsonl'):
        (O['meta_dir'] / name).unlink(missing_ok=True)

    offset, total, goal_stats = 0, 0, []
    for ei in range(n_eps):
        action = store[rigs[0]][f'action_{ei}']
        per_rig = {}
        for r in rigs:
            pose = store[r][f'pose_{ei}']
            dep_dir = stream_dir(O['videos_dir'], 'depth', r)

            def getd(i, _d=dep_dir, _ei=ei):
                p = _d / f'episode_{_ei:06d}_{i}.png'
                if not p.is_file():
                    return None
                return np.asarray(Image.open(p), dtype=np.float32) / DEPTH_SCALE_MM

            g = vpg.build_episode_goals(pose.astype(np.float64), action, r, depth_imgs=getd)
            per_rig[r] = {'pose': pose, 'goal': g['goal'], 'rel': g['relative_goal_frame_id']}
            if r == args.goal_report_rig or (args.goal_report_rig not in rigs and r == rigs[0]):
                goal_stats.append(g['frac_with_goal'])

        res = vw.save_episode_vlnce(out_root, args.out_scene, ei, action, per_rig,
                                    PLACEHOLDER_INSTRUCTION, schema=schema,
                                    global_index_offset=offset)
        offset = res['next_index_offset']
        total += res['frames']
        print(f'[{SCRIPT_NAME}] 조립 ep {ei:>3} {res["frames"]:>4} 프레임 · '
              f'goal 있는 비율 {goal_stats[-1] * 100:.0f}%', flush=True)

    vw.finalize_info_json(out_root, args.out_scene, schema, n_eps, total)
    prov = {
        'produced_by': f'scripts/dataset_converters/gs_vlnpe/apply_real/{SCRIPT_NAME}.py',
        'scene': args.scene, 'out_scene': args.out_scene,
        'paths_json': str(args.paths_json),
        'poses_from': 'our planned path -> vlnce_discretize (forward 0.25 m / turn 15 deg)',
        'pixel_goal_from': 'vlnce_pixel_goal (visible, <=13 forward steps)',
        'instruction': 'PLACEHOLDER — to be filled by vln-annotator',
        'rigs_rendered': rigs, 'rigs_sentinel_filled': missing,
        'episodes': n_eps, 'frames': total,
        'depth_encoding': 'uint16 millimetres, 0 = invalid',
        'render': {'light': args.light, 'rtx_ambient': args.rtx_ambient,
                   'film_iso': args.film_iso},
        'goal_frac_median': float(np.median(goal_stats)) if goal_stats else None,
    }
    (O['meta_dir'] / 'render_provenance.json').write_text(json.dumps(prov, indent=2,
                                                                    ensure_ascii=False))
    return {'episodes': n_eps, 'frames': total,
            'goal_frac_median': prov['goal_frac_median']}


def main() -> int:
    camera_profiles = load_camera_profiles()

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--scene', default='noeun_station_mid', help='논리 scene ID (paths json 이름)')
    ap.add_argument('--out_scene', default=DEFAULT_OUT_SCENE,
                    help="출력 폴더 이름. **`_`를 넣지 말 것** (loader가 key.split('_')로 자른다)")
    ap.add_argument('--paths_json', default=None,
                    help='기본: <out_dir>/paths/<scene>_random.json')
    ap.add_argument('--usd_path', default='data/GS_USDZ/Subway/noeun_station_collision.usdz')
    ap.add_argument('--usd_override', default=None)
    ap.add_argument('--out_dir', default='scripts/dataset_converters/gs_vlnpe/apply_real',
                    help='paths json이 있는 폴더')
    ap.add_argument('--out_root', default='data/InternData-N1-v0.5-mini/vln_ce_noeun')
    ap.add_argument('--rigs', default='all')
    ap.add_argument('--max_episodes', type=int, default=0, help='0이면 전부')
    ap.add_argument('--waypoint_spacing_m', type=float, default=0.5,
                    help='이산화가 목표로 삼을 웨이포인트 간격')
    ap.add_argument('--schema_ref',
                    default='data/InternData-N1-v0.5-mini/vln_ce/traj_data/r2r/'
                            '17DRP5sb8fy/data/chunk-000/episode_000000.parquet',
                    help='parquet 스키마(확장 타입 메타)를 가져올 릴리스 파일')
    ap.add_argument('--goal_report_rig', default='125cm_30deg')
    ap.add_argument('--light', default='ambient_only')
    ap.add_argument('--rtx_ambient', type=float, default=10.0)
    ap.add_argument('--film_iso', type=float, default=70.0)
    ap.add_argument('--per_rig_timeout', type=int, default=14400)
    ap.add_argument('--no_skip_existing', dest='skip_existing', action='store_false')
    ap.add_argument('--skip_assemble', action='store_true', help='렌더만 하고 조립은 건너뛴다')
    ap.add_argument('--log_dir', default='logs/gs-vlnpe/apply_real')
    ap.add_argument('--_worker_rig', default=None, help=argparse.SUPPRESS)
    ap.add_argument('--_sentinel_dir', default=None, help=argparse.SUPPRESS)
    args = ap.parse_args()

    if args.paths_json is None:
        args.paths_json = str(Path(args.out_dir) / 'paths' / f'{args.scene}_random.json')

    if args._worker_rig:
        return render_worker(args)

    # ---- driver ----
    if not Path(args.paths_json).is_file():
        print(f'[{SCRIPT_NAME}] paths json이 없다: {args.paths_json}', file=sys.stderr)
        return 2
    rigs = (list(camera_profiles.vlnce_rig_names()) if args.rigs == 'all'
            else [r for r in args.rigs.split(',') if r])
    eps = load_paths_json(Path(args.paths_json), args.max_episodes)
    out_r2r = Path(args.out_root) / 'traj_data' / 'r2r'

    print(f'[{SCRIPT_NAME}] scene={args.scene} -> {args.out_scene} · 에피소드 {len(eps)} '
          f'· rig {len(rigs)}', flush=True)
    print(f'[{SCRIPT_NAME}] 경로     {args.paths_json}', flush=True)
    print(f'[{SCRIPT_NAME}] 출력     {out_r2r / args.out_scene}', flush=True)

    sentinel_dir = Path(args.log_dir) / SCRIPT_NAME / 'sentinels'
    log_root = Path(args.log_dir) / SCRIPT_NAME / 'logs'
    sentinel_dir.mkdir(parents=True, exist_ok=True)
    log_root.mkdir(parents=True, exist_ok=True)

    t0, done, failed = time.time(), [], []
    for i, rig in enumerate(rigs, 1):
        sent = sentinel_dir / f'{rig}.json'
        if args.skip_existing and sent.is_file():
            rec = json.loads(sent.read_text())
            if rec.get('max_episodes') == args.max_episodes:
                done.append(rec)
                print(f'[{SCRIPT_NAME}] {i}/{len(rigs)} {rig} — 이미 있음, 건너뜀', flush=True)
                continue
        cmd = [ISAAC_PY, str(Path(__file__).resolve()), '--_worker_rig', rig,
               '--_sentinel_dir', str(sentinel_dir),
               '--scene', args.scene, '--out_scene', args.out_scene,
               '--paths_json', args.paths_json, '--usd_path', args.usd_path,
               '--out_dir', args.out_dir, '--out_root', args.out_root,
               '--max_episodes', str(args.max_episodes),
               '--waypoint_spacing_m', str(args.waypoint_spacing_m),
               '--light', args.light, '--rtx_ambient', str(args.rtx_ambient),
               '--film_iso', str(args.film_iso)]
        if args.usd_override:
            cmd += ['--usd_override', args.usd_override]
        lp = log_root / f'{rig}.log'
        ts = time.time()
        with open(lp, 'w') as fh:
            p = subprocess.run(cmd, stdout=fh, stderr=subprocess.STDOUT,
                               timeout=args.per_rig_timeout)
        if sent.is_file():
            rec = json.loads(sent.read_text())
            done.append(rec)
            print(f'[{SCRIPT_NAME}] {i}/{len(rigs)} {rig}  {rec["episodes"]}ep '
                  f'{rec["frames"]}프레임  ({time.time() - ts:.0f}s)', flush=True)
        else:
            failed.append(rig)
            print(f'[{SCRIPT_NAME}] {i}/{len(rigs)} {rig}  실패 (exit {p.returncode}) -> {lp}',
                  flush=True)

    if failed:
        print(f'\n[{SCRIPT_NAME}] 실패한 rig {failed} — 조립을 건너뛴다', flush=True)
        return 1
    if args.skip_assemble:
        print(f'\n[{SCRIPT_NAME}] 렌더만 완료 ({sum(d["frames"] for d in done):,}프레임)', flush=True)
        return 0

    print(f'\n[{SCRIPT_NAME}] 조립 — 픽셀 목표 계산 + parquet/meta 작성', flush=True)
    res = assemble(args, [d['rig'] for d in done], sentinel_dir)
