def render_worker(args) -> int:
    """rig 하나로 전 에피소드를 렌더하고, 프레임별 pose(상대)를 npz로 남긴다."""
    rig = args._worker_rig
    r4 = load_renderer_module()
    camera_profiles = load_camera_profiles()
    import cv2
    import vlnce_discretize as vd
    from geometry_utils import save_jpg

    prof = camera_profiles.get(rig)
    out_root = Path(args.out_root) / 'traj_data' / 'r2r'
    O = scene_paths(out_root, args.out_scene)
    rgb_dir = stream_dir(O['videos_dir'], 'rgb', rig)
    dep_dir = stream_dir(O['videos_dir'], 'depth', rig)
    for d in (rgb_dir, dep_dir):
        d.mkdir(parents=True, exist_ok=True)

    eps = load_paths_json(Path(args.paths_json), args.max_episodes)
    usd_path = r4.resolve_scene_usd(args) if hasattr(r4, 'resolve_scene_usd') else None
    if usd_path is None:
        from esdf_utils import load_scene_usd  # noqa: F401
        usd_path = Path(args.usd_path)

    print(f'[{SCRIPT_NAME}:{rig}] usd={Path(usd_path).name} 에피소드 {len(eps)}개 '
          f'{prof.width}x{prof.height} fx {prof.k[0, 0]:.2f} 높이 {prof.mount_height_m} m '
          f'pitch {prof.pitch_down_deg}°', flush=True)

    cas = r4.build_renderer(prof.width, prof.height, prof.k, usd_path,
                            args.light, None, args.rtx_ambient, args.film_iso,
                            prof.render_near_m, prof.render_far_m)

    t0, total = time.time(), 0
    pose_store, per_ep = {}, []
    for ei, ep in enumerate(eps):
        traj = np.asarray(ep['trajectory'], dtype=np.float64)[:, :2]
        if len(traj) < 3:
            print(f'[{SCRIPT_NAME}:{rig}]   ep {ei} 건너뜀 — 경로가 너무 짧다', flush=True)
            continue
        disc = vd.discretize(traj, waypoint_spacing_m=args.waypoint_spacing_m)
        n = len(disc['action'])

        # rig 높이·pitch를 얹어 절대 pose -> 렌더
        c2w_abs = vd.poses_from_yaw(disc['xy'], disc['yaw'], float(ep['floor_z']),
                                    prof.mount_height_m, prof.pitch_down_deg)
        from geometry_utils import action_to_c2w
        poses_cv = np.stack([action_to_c2w(a, 'cam2world_gl') for a in c2w_abs])
        rgb, depth_m = r4.render_along(cas, poses_cv)

        for i in range(n):
            save_jpg(rgb[i], rgb_dir / f'episode_{ei:06d}_{i}.jpg')
            valid = (np.isfinite(depth_m[i]) & (depth_m[i] > 0)
                     & (depth_m[i] < prof.render_far_m * 0.99))
            cv2.imwrite(str(dep_dir / f'episode_{ei:06d}_{i}.png'),
                        depth_m_to_vlnce_png(depth_m[i], valid))

        # parquet의 `pose.<rig>`는 **에피소드 시작 기준 상대**다
        pose_store[f'pose_{ei}'] = vd.to_start_relative(
            poses_cv, floor_z=float(ep['floor_z'])).astype(np.float32)
        pose_store[f'action_{ei}'] = disc['action'].astype(np.int32)
        total += n
        per_ep.append({'episode': ei, 'src_episode_id': ep.get('episode_id'), 'frames': n,
                       'n_forward': disc['n_forward'], 'n_turn': disc['n_turn'],
                       'path_deviation_m': None, 'end_gap_m': disc['end_gap_m']})
        print(f'[{SCRIPT_NAME}:{rig}]   ep {ei:>3} {n:>4} 프레임 '
              f'(전진 {disc["n_forward"]} 회전 {disc["n_turn"]}) 종점오차 {disc["end_gap_m"]:.3f} m',
              flush=True)

    # pose/action은 조립 단계(driver)가 쓴다 — rig마다 pose가 다르므로 rig별로 남긴다
    pose_path = Path(args._sentinel_dir) / f'pose__{rig}.npz'
    pose_path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(pose_path, **pose_store)

    sent = Path(args._sentinel_dir) / f'{rig}.json'
    sent.write_text(json.dumps({'rig': rig, 'episodes': len(per_ep), 'frames': total,
                                'max_episodes': int(args.max_episodes),
                                'per_episode': per_ep,
                                'elapsed_s': round(time.time() - t0, 1)}, ensure_ascii=False))
    print(f'[{SCRIPT_NAME}:{rig}] 완료 — {len(per_ep)}ep {total}프레임 {time.time() - t0:.0f}s',
          flush=True)
    return 0


